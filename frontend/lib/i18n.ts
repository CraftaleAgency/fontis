/** Name of a corpus language (ISO 639-2), in the UI language. */
const corpusLanguageNames: Record<Locale, Record<string, string>> = {
  en: { eng: "English", ita: "Italian", deu: "German", fra: "French", spa: "Spanish" },
  it: { eng: "inglese", ita: "italiano", deu: "tedesco", fra: "francese", spa: "spagnolo" },
  de: { eng: "Englisch", ita: "Italienisch", deu: "Deutsch", fra: "Französisch", spa: "Spanisch" },
  fr: { eng: "anglais", ita: "italien", deu: "allemand", fra: "français", spa: "espagnol" },
  es: { eng: "inglés", ita: "italiano", deu: "alemán", fra: "francés", spa: "español" },
};

export function corpusLanguageName(locale: Locale, code: string): string {
  return corpusLanguageNames[locale][code] ?? code;
}

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value);
}

